type SlabItem = {
  startWeight: number;
  endWeight: number;
  rateType: "STEP_FIXED" | "RANGE_FIXED" | "RANGE_PER_KG";
  amount: number;
  isAutoGenerated?: boolean;
  keyId: string;
};

function parseCSVRows(text: string, invalidNumMsgFn: (line: number) => string): SlabItem[] {
  const lines = text.split(/\r?\n/);
  const imported: SlabItem[] = [];
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(",");
    if (parts.length < 4) continue;
    const sw = Number.parseFloat(parts[0]);
    const ew = Number.parseFloat(parts[1]);
    const rt = parts[2].trim() as SlabItem["rateType"];
    const amt = Number.parseFloat(parts[3]);
    if (Number.isNaN(sw) || Number.isNaN(ew) || Number.isNaN(amt)) {
      throw new Error(invalidNumMsgFn(i + 1));
    }
    imported.push({
      startWeight: sw,
      endWeight: ew,
      rateType: ["STEP_FIXED", "RANGE_FIXED", "RANGE_PER_KG"].includes(rt) ? rt : "STEP_FIXED",
      amount: amt,
      isAutoGenerated: false,
      keyId: `${sw}-${ew}-${Math.random()}`,
    });
  }
  return imported;
}

function checkSlabContiguityAndMonotonicity(prev: SlabItem, curr: SlabItem, index: number) {
  if (curr.startWeight !== prev.endWeight) {
    throw new Error(
      `Khoảng cân hở ở dòng ${index + 2}: Nấc tiếp theo bắt đầu (${curr.startWeight}kg) không khớp với nấc trước kết thúc (${prev.endWeight}kg).`,
    );
  }
  const prevCost = prev.rateType === "RANGE_PER_KG" ? prev.endWeight * prev.amount : prev.amount;
  const currCost = curr.rateType === "RANGE_PER_KG" ? curr.startWeight * curr.amount : curr.amount;
  if (currCost < prevCost) {
    throw new Error(
      `Vi phạm tính đơn điệu ở dòng ${index + 2}: Giá cước nấc sau (${currCost.toFixed(2)}) nhỏ hơn nấc trước (${prevCost.toFixed(2)}).`,
    );
  }
}

function validateCSVSlabs(imported: SlabItem[]) {
  for (let i = 0; i < imported.length; i++) {
    const curr = imported[i];
    if (curr.startWeight >= curr.endWeight) {
      throw new Error(
        `Nấc cước dòng ${i + 2}: Trọng lượng bắt đầu (${curr.startWeight}kg) phải nhỏ hơn kết thúc (${curr.endWeight}kg).`,
      );
    }
    if (i > 0) {
      checkSlabContiguityAndMonotonicity(imported[i - 1], curr, i);
    }
  }
}

function parseAndValidateCSVText(
  text: string,
  invalidNumMsgFn: (line: number) => string,
): SlabItem[] {
  const imported = parseCSVRows(text, invalidNumMsgFn);
  imported.sort((a, b) => a.startWeight - b.startWeight);
  validateCSVSlabs(imported);
  return imported;
}

