export function RateCardForm({ rateCardId }: RateCardFormProps) {
  const isCreate = rateCardId === null;
  const router = useRouter();
  const t = useToast();
  const tSettings = useTranslations("settings");
  const utils = trpc.useUtils();

  const pathname = usePathname();
  const searchParams = useSearchParams();
  const tabParam = searchParams.get("tab");

  const activeTab = useMemo(() => {
    if (tabParam === "slabs" || tabParam === "logs") return tabParam;
    return "info";
  }, [tabParam]);

  const setActiveTab = useCallback(
    (tab: "info" | "slabs" | "logs") => {
      const params = new URLSearchParams(searchParams.toString());
      params.set("tab", tab);
      const qs = params.toString();
      router.push(`${pathname}${qs ? `?${qs}` : ""}`, { scroll: false });
    },
    [router, pathname, searchParams],
  );

  // Form State
  const {
    register,
    control,
    handleSubmit,
    reset,
    watch,
    setValue,
    formState: { errors, isDirty: isInfoDirty },
  } = useForm<typeof INITIAL_FORM_STATE>({
    resolver: zodResolver(rateCardFormSchema),
    defaultValues: INITIAL_FORM_STATE,
  });

  const formData = watch();

  // Local slabs state
  const [slabs, setSlabs] = useState<SlabItem[]>([]);
  const [initialSlabs, setInitialSlabs] = useState<SlabItem[]>([]);

  // Query groups helper
  const { data: customerGroups } = trpc.viewer.rateCards.listGroups.useQuery();

  // Query rate details
  const { data: existingRate, isLoading: loadingDetails } = trpc.viewer.rateCards.get.useQuery(
    { id: rateCardId ?? 0 },
    { enabled: !isCreate && rateCardId !== null },
  );

  // Query audit logs
  const { data: logs, isLoading: loadingLogs } = trpc.viewer.rateCards.listLogs.useQuery(
    { id: rateCardId ?? 0 },
    { enabled: !isCreate && rateCardId !== null && activeTab === "logs" },
  );

  // Reset/populate form when query loads or creates
  useEffect(() => {
    if (isCreate) {
      reset(INITIAL_FORM_STATE);
      setSlabs([]);
      setInitialSlabs([]);
    } else if (existingRate) {
      const formVal = mapExistingRateToForm(existingRate);
      reset(formVal);
      const slabVal = mapExistingRateToSlabs(existingRate);
      setSlabs(slabVal);
      setInitialSlabs(slabVal);
    }
  }, [isCreate, existingRate, reset]);

  const isSlabsDirty = useMemo(() => {
    if (slabs.length !== initialSlabs.length) return true;
    for (let i = 0; i < slabs.length; i++) {
      const s1 = slabs[i];
      const s2 = initialSlabs[i];
      if (
        s1.startWeight !== s2.startWeight ||
        s1.endWeight !== s2.endWeight ||
        s1.rateType !== s2.rateType ||
        s1.amount !== s2.amount
      ) {
        return true;
      }
    }
    return false;
  }, [slabs, initialSlabs]);

  // Mutations
  const createMut = trpc.viewer.rateCards.create.useMutation({
    onSuccess: (card) => {
      t.toast(tSettings("rates.toastCreateSuccess"), "success");
      utils.viewer.rateCards.list.invalidate();
      router.push(`/settings/rates/${card.id}/edit`);
    },
    onError: (err) => t.toast(formatErrorMessage(err.message), "error"),
  });

  const updateMut = trpc.viewer.rateCards.update.useMutation({
    onSuccess: () => {
      t.toast(tSettings("rates.toastUpdateSuccess"), "success");
      utils.viewer.rateCards.list.invalidate();
      utils.viewer.rateCards.get.invalidate({ id: rateCardId ?? 0 });
    },
    onError: (err) => t.toast(formatErrorMessage(err.message), "error"),
  });

  const importSlabsMut = trpc.viewer.rateCards.importSlabs.useMutation({
    onSuccess: () => {
      t.toast(tSettings("rates.toastImportSuccess"), "success");
      utils.viewer.rateCards.get.invalidate({ id: rateCardId ?? 0 });
    },
    onError: (err) => t.toast(formatErrorMessage(err.message), "error"),
  });

  const handleSaveInfo = handleSubmit(
    (values) => {
      const payload = prepareSavePayload(values);
      if (isCreate) {
        createMut.mutate(payload);
      } else if (rateCardId) {
        updateMut.mutate({ id: rateCardId, ...payload });
      }
    },
    () => {
      t.toast(tSettings("rates.toastValidationError"), "error");
    },
  );

  const handleSaveSlabs = () => {
    if (!rateCardId) return;
    importSlabsMut.mutate({
      rateCardId,
      slabs,
    });
  };

  const isPending = createMut.isPending || updateMut.isPending || importSlabsMut.isPending;

  if (loadingDetails) {
    return (
      <div className="flex min-h-[400px] items-center justify-center">
        <Loader2 className="size-8 animate-spin text-muted-foreground" />
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-6 w-full">
      <FormHeader
        isCreate={isCreate}
        code={formData.code}
        status={formData.status}
        activeTab={activeTab}
        isPending={isPending}
        slabsCount={slabs.length}
        tSettings={tSettings}
        onBack={() => router.push("/settings/rates")}
        onSaveInfo={handleSaveInfo}
        onSaveSlabs={handleSaveSlabs}
        isInfoDirty={isInfoDirty}
        isSlabsDirty={isSlabsDirty}
      />

      <Tabs value={activeTab} onValueChange={(v) => setActiveTab(v as "info" | "slabs" | "logs")}>
        <Card className="rounded-lg border border-border bg-card overflow-hidden">
          {!isCreate && (
            <div className="px-6 pt-6 pb-2 flex items-center">
              <TabsList className="inline-flex h-10 items-center justify-start rounded-lg bg-muted p-1 border border-border">
                <TabsTrigger
                  value="info"
                  className="flex items-center gap-1.5 rounded-md px-4 py-1.5 text-xs md:text-sm font-medium text-muted-foreground transition-all hover:bg-background/50 hover:text-foreground data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow-sm"
                >
                  <Info size={16} className="shrink-0" />
                  <span>{tSettings("rates.tabGeneral")}</span>
                </TabsTrigger>
                <TabsTrigger
                  value="slabs"
                  className="flex items-center gap-1.5 rounded-md px-4 py-1.5 text-xs md:text-sm font-medium text-muted-foreground transition-all hover:bg-background/50 hover:text-foreground data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow-sm"
                >
                  <Scale size={16} className="shrink-0" />
                  <span>{tSettings("rates.tabSlabs")}</span>
                </TabsTrigger>
                <TabsTrigger
                  value="logs"
                  className="flex items-center gap-1.5 rounded-md px-4 py-1.5 text-xs md:text-sm font-medium text-muted-foreground transition-all hover:bg-background/50 hover:text-foreground data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow-sm"
                >
                  <History size={16} className="shrink-0" />
                  <span>{tSettings("rates.tabLogs")}</span>
                </TabsTrigger>
              </TabsList>
            </div>
          )}

          <CardContent className="px-6 pb-6 pt-6">
            <TabsContent value="info" className="mt-0 outline-none">
              <GeneralInfoTab
                control={control}
                register={register}
                errors={errors}
                watch={watch}
                setValue={setValue}
                isCreate={isCreate}
                tSettings={tSettings}
                customerGroups={customerGroups ?? undefined}
                status={formData.status}
              />
            </TabsContent>

            {!isCreate && (
              <>
                <TabsContent value="slabs" className="mt-0 outline-none">
                  <SlabsTab
                    formData={formData}
                    slabs={slabs}
                    setSlabs={setSlabs}
                    tSettings={tSettings}
                  />
                </TabsContent>

                <TabsContent value="logs" className="mt-0 outline-none">
                  <LogsTab logs={logs} loadingLogs={loadingLogs} tSettings={tSettings} />
                </TabsContent>
              </>
            )}
          </CardContent>
        </Card>
      </Tabs>
    </div>
  );
}
