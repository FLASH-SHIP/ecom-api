function getSlabMinCost(slab: SlabItem): number {
  if (slab.rateType === "RANGE_PER_KG") {
    return slab.startWeight * slab.amount;
  }
  return slab.amount;
}

function getSlabMaxCost(slab: SlabItem): number {
  if (slab.rateType === "RANGE_PER_KG") {
    return slab.endWeight * slab.amount;
  }
  return slab.amount;
}

function validateSlabRow(
  curr: SlabItem,
  prev: SlabItem | undefined,
  index: number,
  _totalSlabs: number,
  formData: { minWeight: number; maxWeight: number },
  tSettings: (key: string, values?: Record<string, string | number | Date>) => string,
) {
  if (curr.startWeight >= curr.endWeight) {
    return {
      startWeight: true,
      endWeight: true,
      reason: tSettings("rates.errWeightBounds"),
    };
  }

  const isFirstMinMismatch =
    index === 0 && formData.minWeight != null && curr.startWeight !== formData.minWeight;
  const isGap = prev ? curr.startWeight !== prev.endWeight : false;
  const isMonotonic = prev ? getSlabMinCost(curr) < getSlabMaxCost(prev) : false;

  if (!isFirstMinMismatch && !isGap && !isMonotonic) {
    return {};
  }

  const reason = isFirstMinMismatch
    ? tSettings("rates.errMinWeightMismatch", {
        minWeight: formData.minWeight,
        current: curr.startWeight,
      })
    : isGap
      ? tSettings("rates.errGap", { prevEnd: prev?.endWeight ?? 0 })
      : tSettings("rates.errMonotonicity");

  return {
    startWeight: isFirstMinMismatch || isGap,
    endWeight: false,
    amount: isMonotonic,
    reason,
  };
}

function countSlabErrors(
  slabs: SlabItem[],
  formData: { minWeight: number; maxWeight: number },
  tSettings: (key: string, values?: Record<string, string | number | Date>) => string,
): number {
  let errCount = 0;
  for (let i = 0; i < slabs.length; i++) {
    const err = validateSlabRow(slabs[i], slabs[i - 1], i, slabs.length, formData, tSettings);
    if (err.startWeight || err.endWeight || err.amount) errCount++;
  }
  return errCount;
}

function SlabsTab({ formData, slabs, setSlabs, tSettings, isReadOnly = false }: SlabsTabProps) {
  const t = useToast();
  const templateQuery = trpc.viewer.rateCards.exportSlabsTemplate.useQuery(
    {
      minWeight: formData.minWeight,
      maxWeight: formData.maxWeight,
      weightStep: formData.weightStep,
      rateType: "STEP_FIXED",
    },
    { enabled: false },
  );

  const handleAutoGenerateSlabs = async () => {
    if (isReadOnly) return;
    if (!formData.minWeight && formData.minWeight !== 0) {
      t.toast(tSettings("rates.toastAutoGenerateError"), "error");
      return;
    }
    const res = await templateQuery.refetch();
    if (res.data?.slabs) {
      const generated: SlabItem[] = res.data.slabs.map((s) => ({
        ...s,
        isAutoGenerated: true,
        keyId: `${s.startWeight}-${s.endWeight}-${Math.random()}`,
      }));
      setSlabs(generated);
    }
  };

  const handleDownloadTemplate = () => {
    const csvContent =
      "data:text/csv;charset=utf-8," +
      `${tSettings("rates.csvHeaderStart")},${tSettings("rates.csvHeaderEnd")},${tSettings("rates.csvHeaderType")},${tSettings("rates.csvHeaderAmount")}\n` +
      `0.00,0.50,STEP_FIXED,15.50\n` +
      `0.50,1.00,STEP_FIXED,18.00\n`;
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement("a");
    link.setAttribute("href", encodedUri);
    link.setAttribute("download", `RateCard_Slabs_Template_${formData.code || "export"}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleImportCSV = (e: React.ChangeEvent<HTMLInputElement>) => {
    if (isReadOnly) return;
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = (evt) => {
      try {
        const text = evt.target?.result as string;
        const imported = parseAndValidateCSVText(text, (line) =>
          tSettings("rates.csvInvalidNumber", { line }),
        );
        setSlabs(imported);

        const errCount = countSlabErrors(imported, formData, tSettings);

        if (errCount > 0) {
          t.toast(
            tSettings("rates.toastImportWithErrors", {
              count: imported.length,
              errorCount: errCount,
            }),
            "warning",
          );
        } else {
          t.toast(tSettings("rates.toastReadCSVSuccess", { count: imported.length }), "success");
        }
      } catch (err) {
        t.toast(
          tSettings("rates.toastErrorCSV", {
            message: err instanceof Error ? err.message : "",
          }),
          "error",
        );
      }
    };
    reader.readAsText(file);
    e.target.value = "";
  };

  const handleAddSlabRow = () => {
    if (isReadOnly) return;
    const last = slabs[slabs.length - 1];
    const start = last ? last.endWeight : formData.minWeight;
    const end = start + (formData.weightStep || 0.5);
    setSlabs((prev) => [
      ...prev,
      {
        startWeight: start,
        endWeight: end,
        rateType: "STEP_FIXED",
        amount: 0.0,
        isAutoGenerated: false,
        keyId: `${start}-${end}-${Math.random()}`,
      },
    ]);
  };

  const handleRemoveSlabRow = (index: number) => {
    if (isReadOnly) return;
    setSlabs((prev) => prev.filter((_, i) => i !== index));
  };

  const updateSlabField = (index: number, field: keyof SlabItem, value: unknown) => {
    if (isReadOnly) return;
    setSlabs((prev) =>
      prev.map((s, i) => {
        if (i === index) {
          return { ...s, [field]: value };
        }
        return s;
      }),
    );
  };

  const slabErrors = useMemo(() => {
    const errMap: Record<
      number,
      { startWeight?: boolean; endWeight?: boolean; amount?: boolean; reason?: string }
    > = {};

    for (let i = 0; i < slabs.length; i++) {
      const err = validateSlabRow(slabs[i], slabs[i - 1], i, slabs.length, formData, tSettings);
      if (err.startWeight || err.endWeight || err.amount) {
        errMap[i] = err;
      }
    }

    return errMap;
  }, [slabs, formData, tSettings]);

  const hasMonotonicityWarning = useMemo(() => {
    return Object.values(slabErrors).some((e) => e.amount);
  }, [slabErrors]);

  return (
    <div className="flex flex-col gap-4">
      {isReadOnly && (
        <div className="bg-blue-50 dark:bg-blue-950/40 border border-blue-200 dark:border-blue-900 rounded-md p-3 text-xs text-blue-800 dark:text-blue-200 flex items-center gap-2">
          <Info className="size-4 shrink-0 text-blue-600 dark:text-blue-400" />
          <span>
            Bảng giá ở trạng thái <strong>{formData.status}</strong> đã được khóa nấc cước để đảm
            bảo tính toàn vẹn dữ liệu tính cước đơn hàng.
          </span>
        </div>
      )}

      {hasMonotonicityWarning && (
        <div className="bg-amber-50 dark:bg-amber-950/40 border border-amber-200 dark:border-amber-900 rounded-md p-3 text-xs text-amber-800 dark:text-amber-200 flex items-start gap-2">
          <AlertCircle className="size-4 shrink-0 text-amber-600 mt-0.5" />
          <div>
            <strong>{tSettings("rates.warningLabel")}</strong>{" "}
            {tSettings("rates.warningMonotonicity")}
          </div>
        </div>
      )}

      <div className="flex flex-wrap items-center justify-between gap-3 bg-muted/20 p-3 rounded-lg border border-border">
        <div className="flex flex-wrap gap-2">
          {!isReadOnly && (
            <Button size="sm" variant="outline" className="h-8" onClick={handleAutoGenerateSlabs}>
              <Wand2 className="mr-1.5 size-3.5" />
              {tSettings("rates.btnAutoGenerate")}
            </Button>
          )}
          <Button size="sm" variant="outline" className="h-8" onClick={handleDownloadTemplate}>
            <Download className="mr-1.5 size-3.5" />
            {tSettings("rates.btnDownloadTemplate")}
          </Button>
        </div>

        {!isReadOnly && (
          <div>
            <label className="cursor-pointer">
              <input type="file" accept=".csv" className="hidden" onChange={handleImportCSV} />
              <Button size="sm" variant="secondary" className="h-8 pointer-events-none">
                <Upload className="mr-1.5 size-3.5" />
                {tSettings("rates.btnImportCSV")}
              </Button>
            </label>
          </div>
        )}
      </div>

      <div className="border border-border rounded-lg overflow-hidden">
        <table className="w-full text-xs text-left">
          <thead className="bg-muted/50 border-b border-border text-muted-foreground font-semibold">
            <tr>
              <th className="px-3 py-2">{tSettings("rates.colStart")}</th>
              <th className="px-3 py-2">{tSettings("rates.colEnd")}</th>
              <th className="px-3 py-2">{tSettings("rates.colSlabType")}</th>
              <th className="px-3 py-2">
                {tSettings("rates.colAmount", { currency: formData.currency })}
              </th>
              {!isReadOnly && (
                <th className="px-3 py-2 text-center w-20 whitespace-nowrap">
                  {tSettings("rates.colDelete")}
                </th>
              )}
            </tr>
          </thead>
          <tbody className="divide-y divide-border">
            {slabs.map((slab, index) => {
              const err = slabErrors[index];
              return (
                <tr
                  key={slab.keyId ?? index}
                  className={cn("hover:bg-muted/20", err && "bg-destructive/5")}
                >
                  <td className="px-3 py-1.5">
                    <Input
                      type="number"
                      step={0.01}
                      value={slab.startWeight}
                      onChange={(e) =>
                        updateSlabField(index, "startWeight", Number(e.target.value))
                      }
                      disabled={isReadOnly || slab.isAutoGenerated}
                      className={cn(
                        "h-7 text-xs px-2",
                        err?.startWeight &&
                          "border-destructive text-destructive bg-destructive/10 focus-visible:ring-destructive font-medium",
                      )}
                    />
                  </td>
                  <td className="px-3 py-1.5">
                    <Input
                      type="number"
                      step={0.01}
                      value={slab.endWeight}
                      onChange={(e) => updateSlabField(index, "endWeight", Number(e.target.value))}
                      disabled={isReadOnly || slab.isAutoGenerated}
                      className={cn(
                        "h-7 text-xs px-2",
                        err?.endWeight &&
                          "border-destructive text-destructive bg-destructive/10 focus-visible:ring-destructive font-medium",
                      )}
                    />
                  </td>
                  <td className="px-3 py-1.5">
                    <Select
                      value={slab.rateType}
                      onValueChange={(v) =>
                        updateSlabField(index, "rateType", v as SlabItem["rateType"])
                      }
                      disabled={isReadOnly || slab.isAutoGenerated}
                    >
                      <SelectTrigger className="h-7 text-xs px-2">
                        <SelectValue />
                      </SelectTrigger>
                      <SelectContent>
                        <SelectItem value="STEP_FIXED">
                          {tSettings("rates.typeStepFixed")}
                        </SelectItem>
                        <SelectItem value="RANGE_FIXED">
                          {tSettings("rates.typeRangeFixed")}
                        </SelectItem>
                        <SelectItem value="RANGE_PER_KG">
                          {tSettings("rates.typeRangePerKg")}
                        </SelectItem>
                      </SelectContent>
                    </Select>
                  </td>
                  <td className="px-3 py-1.5">
                    <Input
                      type="number"
                      step={0.01}
                      value={slab.amount}
                      onChange={(e) => updateSlabField(index, "amount", Number(e.target.value))}
                      disabled={isReadOnly}
                      className={cn(
                        "h-7 text-xs px-2",
                        err?.amount &&
                          "border-destructive text-destructive bg-destructive/10 focus-visible:ring-destructive font-medium",
                      )}
                    />
                    {err?.reason && (
                      <span className="text-[10px] text-destructive block mt-0.5 font-medium">
                        {err.reason}
                      </span>
                    )}
                  </td>
                  {!isReadOnly && (
                    <td className="px-3 py-1.5 text-center">
                      <Button
                        size="icon"
                        variant="ghost"
                        className="size-7 text-destructive"
                        onClick={() => handleRemoveSlabRow(index)}
                      >
                        <Trash2 className="size-3.5" />
                      </Button>
                    </td>
                  )}
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      {!isReadOnly && (
        <Button size="sm" variant="outline" className="w-fit" onClick={handleAddSlabRow}>
          <Plus className="mr-1.5 size-3.5" />
          {tSettings("rates.btnAddSlab")}
        </Button>
      )}
    </div>
  );
}

