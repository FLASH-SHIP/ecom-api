function formatErrorMessage(msg: string): string {
  if (!msg) return "";
  const parts = msg
    .split(/,\s*/)
    .map((p) => p.trim())
    .filter(Boolean);
  const uniqueParts = Array.from(new Set(parts));
  return uniqueParts.join(", ");
}

