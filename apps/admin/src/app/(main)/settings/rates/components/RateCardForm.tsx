type SlabItem = {
  startWeight: number;
  endWeight: number;
  rateType: "STEP_FIXED" | "RANGE_FIXED" | "RANGE_PER_KG";
  amount: number;
  isAutoGenerated?: boolean;
  keyId: string;
};

// 1. Monotonicity check logic extracted to reduce complexity
function checkSlabsMonotonicity(slabs: SlabItem[]): boolean {
  const sorted = [...slabs].sort((a, b) => a.startWeight - b.startWeight);
  for (let i = 1; i < sorted.length; i++) {
    const prev = sorted[i - 1];
    const curr = sorted[i];
    if (!prev || !curr) continue;

    const costPrevEnd =
      prev.rateType === "RANGE_PER_KG" ? prev.endWeight * prev.amount : prev.amount;
    const costCurrentStart =
      curr.rateType === "RANGE_PER_KG" ? curr.startWeight * curr.amount : curr.amount;

    if (costCurrentStart < costPrevEnd) {
      return false;
    }
  }
  return true;
}

// 2. CSV parsing logic extracted to reduce complexity
function parseSlabsCSV(
  text: string,
  tSettings: (key: string, values?: Record<string, string | number | Date>) => string,
): SlabItem[] {
  const lines = text
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  const parsed: SlabItem[] = [];
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    if (!line) continue;
    const parts = line.split(",");
    if (parts.length < 4) continue;
    const startWeight = Number(parts[0]);
    const endWeight = Number(parts[1]);
    const rateType = parts[2] as SlabItem["rateType"];
    const amount = Number(parts[3]);

    if (Number.isNaN(startWeight) || Number.isNaN(endWeight) || Number.isNaN(amount)) {
      throw new Error(tSettings("rates.csvInvalidNumber", { line: i + 1 }));
    }
    parsed.push({
      startWeight,
      endWeight,
      rateType,
      amount,
      keyId: `${startWeight}-${endWeight}-${Math.random()}`,
    });
  }
  return parsed;
}

// 3. Auto generation logic extracted to reduce complexity
function generateSlabItems(minW: number, maxW: number, step: number): SlabItem[] {
  const generated: SlabItem[] = [];
  let current = minW;
  while (current < maxW) {
    const next = Math.min(maxW, Number((current + step).toFixed(3)));
    generated.push({
      startWeight: current,
      endWeight: next,
      rateType: "STEP_FIXED",
      amount: 0.0,
      isAutoGenerated: true,
      keyId: `${current}-${next}-${Math.random()}`,
    });
    current = next;
  }
  return generated;
}

// 4. Add slab calculation logic extracted to reduce complexity
function calculateNewSlabRow(
  slabs: SlabItem[],
  minWeight: number,
  maxWeight: number,
  weightStep: number,
): SlabItem {
  const sorted = [...slabs].sort((a, b) => a.startWeight - b.startWeight);
  const lastSlab = sorted[sorted.length - 1];
  const start = lastSlab ? lastSlab.endWeight : minWeight;
  const step = weightStep || 0.5;
  const end =
    start >= maxWeight
      ? Number((start + step).toFixed(3))
      : Math.min(maxWeight, Number((start + step).toFixed(3)));
  return {
    startWeight: start,
    endWeight: end,
    rateType: lastSlab ? lastSlab.rateType : "STEP_FIXED",
    amount: 0.0,
    keyId: `${start}-${end}-${Math.random()}`,
  };
}

