interface SlabsTabProps {
  formData: {
    code: string;
    currency: string;
    minWeight: number;
    maxWeight: number;
    weightStep: number;
  };
  slabs: SlabItem[];
  setSlabs: React.Dispatch<React.SetStateAction<SlabItem[]>>;
  tSettings: (key: string, values?: Record<string, string | number | Date>) => string;
}

function SlabsTab({ formData, slabs, setSlabs, tSettings }: SlabsTabProps) {
  const t = useToast();

  // Generate template slabs automatically based on weight step
  const handleAutoGenerateSlabs = () => {
    const minW = Number(formData.minWeight);
    const maxW = Number(formData.maxWeight);
    const step = Number(formData.weightStep);

    if (maxW <= minW || step <= 0) {
      t.toast(tSettings("rates.toastAutoGenerateError"), "error");
      return;
    }

    setSlabs(generateSlabItems(minW, maxW, step));
  };

  const handleAddSlabRow = () => {
    const minW = Number(formData.minWeight);
    const maxW = Number(formData.maxWeight);
    const step = Number(formData.weightStep);
    setSlabs([...slabs, calculateNewSlabRow(slabs, minW, maxW, step)]);
  };

  const handleRemoveSlabRow = (index: number) => {
    const next = [...slabs];
    next.splice(index, 1);
    setSlabs(next);
  };

  const updateSlabField = <K extends keyof SlabItem>(index: number, field: K, val: SlabItem[K]) => {
    const next = [...slabs];
    const item = next[index];
    if (item) {
      next[index] = {
        ...item,
        [field]: val,
      };
      setSlabs(next);
    }
  };

  // Monotonicity checker
  const isMonotonic = useMemo(() => checkSlabsMonotonicity(slabs), [slabs]);

  // Export CSV
  const handleExportCSV = () => {
    const headers = `${tSettings("rates.csvHeaderStart")},${tSettings("rates.csvHeaderEnd")},${tSettings("rates.csvHeaderType")},${tSettings("rates.csvHeaderAmount")}\n`;
    const rowsText = slabs
      .map((s) => `${s.startWeight},${s.endWeight},${s.rateType},${s.amount}`)
      .join("\n");
    const blob = new Blob([headers + rowsText], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.setAttribute("href", url);
    link.setAttribute("download", `template-nac-cuoc-${formData.code || "rate-card"}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  // Import CSV
  const handleImportCSV = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (evt) => {
      try {
        const text = evt.target?.result as string;
        const parsed = parseSlabsCSV(text, tSettings);
        setSlabs(parsed);
        t.toast(tSettings("rates.toastReadCSVSuccess", { count: parsed.length }), "success");
      } catch (err) {
        const errMsg = err instanceof Error ? err.message : String(err);
        t.toast(tSettings("rates.toastErrorCSV", { message: errMsg }), "error");
      }
    };
    reader.readAsText(file);
    e.target.value = "";
  };

  return (
    <div className="flex flex-col gap-5">
      {/* Monotonicity Warning Banner */}
      {!isMonotonic && (
        <div className="flex gap-2 rounded-md border border-amber-300 bg-amber-50 dark:bg-amber-950/20 p-3 text-xs text-amber-800 dark:text-amber-300">
          <AlertTriangle className="size-4 shrink-0 mt-0.5" />
          <div>
            <span className="font-semibold">{tSettings("rates.warningLabel")}</span>{" "}
            {tSettings("rates.warningMonotonicity")}
          </div>
        </div>
      )}

      {/* Utility Tools row */}
      <div className="flex flex-wrap gap-2 justify-between items-center bg-muted/30 p-3 rounded-lg border border-border">
        <div className="flex gap-1.5">
          <Button size="sm" variant="outline" className="h-8" onClick={handleAutoGenerateSlabs}>
            <RefreshCw className="mr-1.5 size-3" />
            {tSettings("rates.btnAutoGenerate")}
          </Button>
          <Button size="sm" variant="outline" className="h-8" onClick={handleExportCSV}>
            <Download className="mr-1.5 size-3" />
            {tSettings("rates.btnDownloadTemplate")}
          </Button>
        </div>

        <div className="relative">
          <input
            type="file"
            accept=".csv"
            onChange={handleImportCSV}
            className="absolute inset-0 opacity-0 cursor-pointer w-full h-full"
            id="csv-file-input"
          />
          <Button size="sm" variant="outline" className="h-8">
            <Upload className="mr-1.5 size-3" />
            {tSettings("rates.btnImportCSV")}
          </Button>
        </div>
      </div>

      {/* Slabs Grid Table */}
      <div className="border border-border rounded-lg overflow-hidden bg-card">
        <table className="w-full text-left border-collapse text-xs">
          <thead>
            <tr className="bg-muted/40 border-b border-border">
              <th className="px-3 py-2 font-semibold text-muted-foreground w-28 text-center">
                {tSettings("rates.colStart")}
              </th>
              <th className="px-3 py-2 font-semibold text-muted-foreground w-28 text-center">
                {tSettings("rates.colEnd")}
              </th>
              <th className="px-3 py-2 font-semibold text-muted-foreground w-64">
                {tSettings("rates.colType")}
              </th>
              <th className="px-3 py-2 font-semibold text-muted-foreground">
                {tSettings("rates.colAmount", { currency: formData.currency })}
              </th>
              <th
                className="px-3 py-2 text-center w-12"
                aria-label={tSettings("rates.colDelete")}
              />
            </tr>
          </thead>
          <tbody>
            {slabs.map((slab, index) => (
              <tr
                key={slab.keyId}
                className="border-b border-border last:border-0 hover:bg-muted/10"
              >
                <td className="px-3 py-1.5 w-28">
                  <Input
                    type="number"
                    step={formData.weightStep || 0.1}
                    value={slab.startWeight}
                    onChange={(e) => updateSlabField(index, "startWeight", Number(e.target.value))}
                    className="h-7 text-xs px-2 text-center"
                    disabled={slab.isAutoGenerated}
                  />
                </td>
                <td className="px-3 py-1.5 w-28">
                  <Input
                    type="number"
                    step={formData.weightStep || 0.1}
                    value={slab.endWeight}
                    onChange={(e) => updateSlabField(index, "endWeight", Number(e.target.value))}
                    className="h-7 text-xs px-2 text-center"
                    disabled={slab.isAutoGenerated}
                  />
                </td>
                <td className="px-3 py-1.5 w-64">
                  <Select
                    value={slab.rateType}
                    onValueChange={(v) =>
                      updateSlabField(index, "rateType", v as SlabItem["rateType"])
                    }
                    disabled={slab.isAutoGenerated}
                  >
                    <SelectTrigger className="h-7 text-xs px-2">
                      <SelectValue />
                    </SelectTrigger>
                    <SelectContent>
                      <SelectItem value="STEP_FIXED">{tSettings("rates.typeStepFixed")}</SelectItem>
                      <SelectItem value="RANGE_FIXED">
                        {tSettings("rates.typeRangeFixed")}
                      </SelectItem>
                      <SelectItem value="RANGE_PER_KG">
                        {tSettings("rates.typeRangePerKg")}
                      </SelectItem>
                    </SelectContent>
                  </Select>
                </td>
                <td className="px-3 py-1.5">
                  <Input
                    type="number"
                    step={0.01}
                    value={slab.amount}
                    onChange={(e) => updateSlabField(index, "amount", Number(e.target.value))}
                    className="h-7 text-xs px-2 font-medium"
                  />
                </td>
                <td className="px-3 py-1.5 text-center">
                  {!slab.isAutoGenerated && (
                    <button
                      type="button"
                      onClick={() => handleRemoveSlabRow(index)}
                      className="text-destructive hover:bg-red-50 p-1 rounded-md transition-colors"
                    >
                      <Trash2 size={14} />
                    </button>
                  )}
                </td>
              </tr>
            ))}
            {slabs.length === 0 && (
              <tr>
                <td
                  colSpan={5}
                  className="py-8 text-center text-muted-foreground italic bg-muted/5"
                >
                  {tSettings("rates.noSlabs")}
                </td>
              </tr>
            )}
          </tbody>
        </table>
      </div>

      <div className="flex gap-2">
        <Button size="sm" variant="outline" className="h-8 w-fit" onClick={handleAddSlabRow}>
          <Plus className="mr-1.5 size-3" />
          {tSettings("rates.btnAddSlab")}
        </Button>
      </div>
    </div>
  );
}

